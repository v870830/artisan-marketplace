import os
import sqlite3
import psycopg


# --------------------------------------------------
# STEP 1: SET DATABASE PATHS
# --------------------------------------------------

SQLITE_FILE = "database.db"

DATABASE_URL = os.environ.get("DATABASE_URL")


if not DATABASE_URL:
    raise SystemExit(
        "ERROR: DATABASE_URL is not set."
    )


# --------------------------------------------------
# STEP 2: CONNECT TO LOCAL SQLITE DATABASE
# --------------------------------------------------

sqlite_connection = sqlite3.connect(
    f"file:{SQLITE_FILE}?mode=ro",
    uri=True
)

sqlite_connection.row_factory = sqlite3.Row


# --------------------------------------------------
# STEP 3: CONNECT TO NEON POSTGRESQL
# --------------------------------------------------

try:
    with psycopg.connect(DATABASE_URL) as postgres_connection:

        with postgres_connection.cursor() as cursor:

            # ------------------------------------------
            # CREATE USERS TABLE
            # ------------------------------------------

            cursor.execute("""
                CREATE TABLE IF NOT EXISTS users (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name TEXT NOT NULL,
                    email TEXT NOT NULL UNIQUE,
                    password TEXT NOT NULL,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
            """)

            print("Users table created or already exists.")


            # ------------------------------------------
            # CREATE PRODUCTS TABLE
            # ------------------------------------------

            cursor.execute("""
                CREATE TABLE IF NOT EXISTS products (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name TEXT NOT NULL,
                    category TEXT NOT NULL,
                    price DOUBLE PRECISION NOT NULL,
                    location TEXT NOT NULL,
                    artisan TEXT NOT NULL,
                    description TEXT NOT NULL,
                    image TEXT,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    user_id INTEGER REFERENCES users(id)
                )
            """)

            print("Products table created or already exists.")


            # ------------------------------------------
            # CREATE ORDERS TABLE
            # ------------------------------------------

            cursor.execute("""
                CREATE TABLE IF NOT EXISTS orders (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    product_id INTEGER NOT NULL REFERENCES products(id),
                    buyer_name TEXT NOT NULL,
                    quantity INTEGER NOT NULL DEFAULT 1,
                    total_price DOUBLE PRECISION NOT NULL,
                    status TEXT NOT NULL DEFAULT 'Pending',
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    buyer_id INTEGER REFERENCES users(id),
                    cancelled_by TEXT
                )
            """)

            print("Orders table created or already exists.")


            # ------------------------------------------
            # STEP 4: COPY SQLITE DATA TO NEON
            # ------------------------------------------

            tables = (
                "users",
                "products",
                "orders"
            )

            for table in tables:

                print(f"\nMigrating {table}...")

                # Read all records from the local database.
                rows = sqlite_connection.execute(
                    f"SELECT * FROM {table} ORDER BY id"
                ).fetchall()

                if not rows:
                    print(f"{table}: no local records found.")
                    continue

                # Get the column names.
                columns = rows[0].keys()

                column_sql = ", ".join(
                    f'"{column}"'
                    for column in columns
                )

                # Create one placeholder for each column.
                placeholders = ", ".join(
                    ["%s"] * len(columns)
                )

                # Prepare the INSERT query.
                insert_sql = (
                    f'INSERT INTO "{table}" ({column_sql}) '
                    f"VALUES ({placeholders}) "
                    f"ON CONFLICT (id) DO NOTHING"
                )

                # Insert records into Neon.
                cursor.executemany(
                    insert_sql,
                    [
                        tuple(row)
                        for row in rows
                    ]
                )

                print(
                    f"{table}: processed {len(rows)} local records."
                )


            # ------------------------------------------
            # STEP 5: SYNCHRONIZE ID SEQUENCES
            # ------------------------------------------

            for table in tables:

                cursor.execute(
                    f"""
                    SELECT setval(
                        pg_get_serial_sequence(%s, 'id'),
                        GREATEST(
                            COALESCE(
                                (SELECT MAX(id) FROM {table}),
                                1
                            ),
                            1
                        ),
                        (
                            SELECT COUNT(*) > 0
                            FROM {table}
                        )
                    )
                    """,
                    (table,)
                )

                print(
                    f"{table}: ID sequence synchronized."
                )


        # The cursor block has ended here.
        # Create a NEW cursor for verification.

        with postgres_connection.cursor() as verify_cursor:

            # ------------------------------------------
            # STEP 6: VERIFY MIGRATED RECORD COUNTS
            # ------------------------------------------

            print("\n========== MIGRATION VERIFICATION ==========")

            for table in (
                "users",
                "products",
                "orders"
            ):

                verify_cursor.execute(
                    f'SELECT COUNT(*) FROM "{table}"'
                )

                count = verify_cursor.fetchone()[0]

                print(
                    f"Neon {table} count: {count}"
                )

            print("============================================")


finally:

    # Close the local SQLite database.
    sqlite_connection.close()


print("\nMigration script finished.")