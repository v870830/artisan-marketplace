MODEL_PATH = os.path.join(
    os.path.dirname(__file__),
    "flan_t5_artisan"
)

tokenizer = None
model = None

def load_ai_model():
    global tokenizer, model

    if model is None:
        tokenizer = AutoTokenizer.from_pretrained(MODEL_PATH)
        model = AutoModelForSeq2SeqLM.from_pretrained(MODEL_PATH)

    return tokenizer, model


