@app.route("/generate-description", methods=["POST"])
@login_required
def generate_description():

    data = request.get_json(silent=True) or {}
    name = str(data.get("name") or "").strip()
    details = str(data.get("details") or "").strip()

    if not name or not details:
        return jsonify({"error": "Enter product name and details."}), 400

    try:
        tokenizer, model = load_ai_model()

        prompt = (
        f"Write an attractive and professional product description "
        f"for an online handmade products marketplace. "
        f"Product name: {name}. "
        f"Product details: {details}. "
        f"Write 2 to 3 complete sentences highlighting the product's "
        f"features, material, quality and uses. "
        f"Do not repeat the input. Do not add imaginary facts."
        )

        inputs = tokenizer(
            prompt,
            return_tensors="pt",
            max_length=128,
            truncation=True
        )

        with torch.no_grad():
            outputs = model.generate(
                **inputs,
                max_length=100,
                num_beams=4,
                early_stopping=True
            )

        description = tokenizer.decode(
            outputs[0],
            skip_special_tokens=True
        )

        return jsonify({"description": description})

    except Exception as e:
        print("AI Generation Error:", e)
        return jsonify({"error": "AI description generation failed."}), 500

# Artisan Studio — each artisan sees only their own products
@app.route("/artisan", methods=["GET", "POST"])
@login_required
def artisan():

    # Handle new product submission
    if request.method == "POST":
        name = request.form.get("name", "").strip()
        category = request.form.get("category", "").strip()
        location = request.form.get("location", "").strip()
        artisan_name = request.form.get("artisan", "").strip()
        description = request.form.get("description", "").strip()

        try:
            price = float(request.form.get("price", "0"))
        except ValueError:
            price = 0

        # Read the uploaded product image
        image_file = request.files.get("image")
        image_data = None

        if image_file and image_file.filename:
            allowed_types = {"image/jpeg", "image/png", "image/webp"}

            if image_file.mimetype not in allowed_types:
                flash("Please upload a JPG, PNG, or WebP image.", "error")
                return redirect(url_for("artisan"))

            image_bytes = image_file.read()

            if len(image_bytes) > 5 * 1024 * 1024:
                flash("Image must be smaller than 5 MB.", "error")
                return redirect(url_for("artisan"))

            image_data = (
                "data:"
                + image_file.mimetype
                + ";base64,"
                + base64.b64encode(image_bytes).decode("utf-8")
            )

        # Validate product details
        if not all([name, category, location, artisan_name, description]):
            flash("Please fill in all product details.", "error")
            return redirect(url_for("artisan"))

        if price <= 0:
            flash("Please enter a valid price.", "error")
            return redirect(url_for("artisan"))

        if image_data is None:
            flash("Please select a product image.", "error")
            return redirect(url_for("artisan"))

        # Save the product with the logged-in user's ID
        connection = get_db_connection()

        connection.execute("""
            INSERT INTO products
            (name, category, price, location, artisan, description, image, user_id)
            VALUES (%s, %s, %s, %s, %s, %s, %s, %s)
        """, (
            name,
            category,
            price,
            location,
            artisan_name,
            description,
            image_data,
            session["user_id"]
        ))

        connection.commit()
        connection.close()

        flash("Product published successfully!", "success")
        return redirect(url_for("artisan"))

    # Fetch only products owned by the logged-in artisan
    connection = get_db_connection()

    products = connection.execute("""
    SELECT *
    FROM products
    WHERE user_id = %s AND is_active = TRUE
    ORDER BY id DESC
    """, (session["user_id"],)).fetchall()

    connection.close()

    return render_template("artisan.html", products=products)

