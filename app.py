# Create a buyer order

@app.route("/place-order/<int:product_id>", methods=["POST"])
@login_required
def place_order(product_id):
    buyer_name = request.form.get("buyer_name", "").strip()

    try:
        quantity = int(request.form.get("quantity", "1"))
    except ValueError:
        quantity = 0

    if not buyer_name or quantity < 1 or quantity > 100:
        flash("Please enter a valid buyer name and quantity.", "error")
        return redirect(url_for("buyer"))

    connection = get_db_connection()

    product = connection.execute(
        "SELECT * FROM products WHERE id = %s",
        (product_id,)
    ).fetchone()

    if product is None:
        connection.close()
        flash("Product not found.", "error")
        return redirect(url_for("buyer"))

    total_price = product["price"] * quantity

    connection.execute("""
        INSERT INTO orders
        (product_id, buyer_name, quantity, total_price, buyer_id)
        VALUES (%s, %s, %s, %s, %s)
    """, (
        product_id,
        buyer_name,
        quantity,
        total_price,
        session["user_id"]
    ))

    connection.commit()
    connection.close()

    flash("Order placed successfully!", "success")
    return redirect(url_for("my_orders"))



