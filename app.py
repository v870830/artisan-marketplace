# Check whether the user is logged in
def login_required(route_function):
    @wraps(route_function)
    def wrapper(*args, **kwargs):
        if "user_id" not in session:
            flash("Please log in first.", "error")
            return redirect(url_for("login"))

        return route_function(*args, **kwargs)

    return wrapper


# Neon PostgreSQL connection string (set as DATABASE_URL environment variable)
DATABASE_URL = os.environ.get("DATABASE_URL")


def get_db_connection():
    if not DATABASE_URL:
        raise RuntimeError("DATABASE_URL is not configured.")

    return psycopg.connect(
        DATABASE_URL,
        row_factory=dict_row
    )


# Create database tables if they do not exist
def initialize_database():
    with get_db_connection() as connection:
        connection.execute("""
            CREATE TABLE IF NOT EXISTS users (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL,
                email TEXT NOT NULL UNIQUE,
                password TEXT NOT NULL,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        """)

        connection.execute("""
            CREATE TABLE IF NOT EXISTS products (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL,
                category TEXT NOT NULL,
                price DOUBLE PRECISION NOT NULL,
                location TEXT NOT NULL,
                artisan TEXT NOT NULL,
                description TEXT NOT NULL,
                image TEXT,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                user_id INTEGER REFERENCES users(id)
            )
        """)

        connection.execute("""
                ALTER TABLE products 
                ADD COLUMN IF NOT EXISTS is_active BOOLEAN DEFAULT TRUE
                """)

        connection.execute("""
            CREATE TABLE IF NOT EXISTS orders (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                product_id INTEGER NOT NULL REFERENCES products(id),
                buyer_name TEXT NOT NULL,
                quantity INTEGER NOT NULL DEFAULT 1,
                total_price DOUBLE PRECISION NOT NULL,
                status TEXT NOT NULL DEFAULT 'Pending',
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                buyer_id INTEGER REFERENCES users(id),
                cancelled_by TEXT
            )
        """)




# Register a new artisan
@app.route("/register", methods=["GET", "POST"])
def register():
    if request.method == "POST":
        name = request.form.get("name", "").strip()
        email = request.form.get("email", "").strip().lower()
        password = request.form.get("password", "")

        # Validate registration fields
        if not name or not email or not password:
            flash("Please fill in all fields.", "error")
            return redirect(url_for("register"))

        if len(password) < 6:
            flash("Password must contain at least 6 characters.", "error")
            return redirect(url_for("register"))

        # Save the account with a hashed password
        hashed_password = generate_password_hash(password)

        connection = get_db_connection()

        try:
            connection.execute("""
                INSERT INTO users (name, email, password)
                VALUES (%s, %s, %s)
            """, (name, email, hashed_password))

            connection.commit()

        except IntegrityError:
            flash("This email is already registered. Please log in.", "error")
            return redirect(url_for("login"))

        finally:
            connection.close()

        flash("Registration successful! Please log in.", "success")
        return redirect(url_for("login"))

    return render_template("register.html")


# Log in an existing artisan
@app.route("/login", methods=["GET", "POST"])
def login():
    if request.method == "POST":
        email = request.form.get("email", "").strip().lower()
        password = request.form.get("password", "")

        connection = get_db_connection()

        user = connection.execute("""
            SELECT * FROM users WHERE email = %s
        """, (email,)).fetchone()

        connection.close()

      
        if user and check_password_hash(user["password"], password):
            session.clear()

            # Keep the user logged in across browser restarts
            session.permanent = True

            session["user_id"] = user["id"]
            session["user_name"] = user["name"]

            flash("Welcome back, " + user["name"] + "!", "success")
            return redirect(url_for("artisan"))

        flash("Invalid email or password.", "error")
        return redirect(url_for("login"))



    return render_template("login.html")


